import { Client } from 'pg';
import { createMockServer, MockServer } from '@nocobase/test';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { DATA_SOURCE_TYPE, NAMESPACE } from '../../constants';
import { PostgresDataSource } from '../postgres-datasource';
import { PluginDataSourcePostgresServer } from '../plugin';

const disposablePostgresEnabled = process.env.NOCOBASE_POSTGRES_DISPOSABLE_TEST === '1';
const host = process.env.NOCOBASE_POSTGRES_TEST_HOST;
const port = Number(process.env.NOCOBASE_POSTGRES_TEST_PORT);
const database = process.env.NOCOBASE_POSTGRES_TEST_DATABASE;
const username = process.env.NOCOBASE_POSTGRES_TEST_USERNAME;
const password = process.env.NOCOBASE_POSTGRES_TEST_PASSWORD;
const testSchema = `codex_pg_test_${process.pid}_${Date.now()}`;
const sourceKey = 'postgres-resource-test';

const hasPostgresConfig = Boolean(host && port && database && username);
const testOptions = {
  host,
  port,
  database,
  username,
  password,
  schema: testSchema,
};

describe.skipIf(!disposablePostgresEnabled || !hasPostgresConfig)('PostgreSQL data source integration', () => {
  let setupClient: Client;
  let dataSource: PostgresDataSource;
  let app: MockServer;

  beforeAll(async () => {
    setupClient = new Client({ host, port, database, user: username, password });
    await setupClient.connect();
    await setupClient.query(`CREATE SCHEMA "${testSchema}"`);
    await setupClient.query(`
      CREATE TABLE "${testSchema}".orders (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        external_code TEXT
      )
    `);
    await setupClient.query(`INSERT INTO "${testSchema}".orders (name) VALUES ('Existing order')`);
    await setupClient.query(`
      CREATE TABLE "${testSchema}".composite_records (
        tenant_id INTEGER NOT NULL,
        record_id INTEGER NOT NULL,
        value TEXT,
        PRIMARY KEY (tenant_id, record_id)
      )
    `);
    await setupClient.query(`
      CREATE TABLE "${testSchema}".uuid_identity_records (
        id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
        sequence_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
        external_key UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE
      )
    `);
    await setupClient.query(`
      CREATE VIEW "${testSchema}".order_names AS
      SELECT id, name FROM "${testSchema}".orders
    `);

    dataSource = new PostgresDataSource({ ...testOptions, name: 'postgres-test' });
    await dataSource.load();

    app = await createMockServer({
      plugins: ['nocobase', 'data-source-manager', [PluginDataSourcePostgresServer, { name: NAMESPACE }]],
    });
    const sourceOptions = {
      ...testOptions,
      addAllCollections: false,
      autoDiscover: false,
      selectedCollections: [],
    };
    const createSourceResponse = await app
      .agent()
      .resource('dataSources')
      .create({
        values: {
          key: sourceKey,
          type: DATA_SOURCE_TYPE,
          displayName: 'PostgreSQL test source',
          enabled: true,
          options: sourceOptions,
        },
      });
    expect(createSourceResponse.status, createSourceResponse.text).toBe(200);
    for (let attempt = 0; attempt < 100 && !app.dataSourceManager.get(sourceKey); attempt++) {
      await new Promise<void>((resolve) => setTimeout(resolve, 50));
    }
    const createdSource = app.dataSourceManager.get(sourceKey) as PostgresDataSource | undefined;
    if (!createdSource) throw new Error('The host did not finish loading the PostgreSQL data source');
    await createdSource.collectionManager.db.sequelize.authenticate();
  }, 120000);

  afterAll(async () => {
    if (app) await app.destroy();
    if (dataSource) await dataSource.close();
    if (setupClient) {
      await setupClient.query(`DROP SCHEMA IF EXISTS "${testSchema}" CASCADE`);
      await setupClient.end();
    }
  });

  it('discovers tables and views, and loads a table selected by the host action', async () => {
    const tables = await dataSource.readTables();
    expect(tables.map(({ name }) => name)).toEqual([
      'composite_records',
      'order_names',
      'orders',
      'uuid_identity_records',
    ]);

    const selected = new PostgresDataSource({
      ...testOptions,
      name: 'postgres-selected-test',
      addAllCollections: false,
      autoDiscover: false,
    });
    try {
      await selected.load();
      expect(selected.collectionManager.getCollections()).toHaveLength(0);

      await selected.loadTables({} as never, ['orders']);
      expect(selected.collectionManager.getCollections().map((collection) => collection.name)).toEqual(['orders']);
    } finally {
      await selected.close();
    }
  });

  it('uses the host HTTP resources to import tables, create collections and fields, and reject dependent deletes', async () => {
    const readResponse = await app
      .agent()
      .resource('dataSources')
      .readTables({
        values: {
          dataSourceKey: sourceKey,
          dbOptions: { type: DATA_SOURCE_TYPE, ...testOptions },
        },
      });
    expect(readResponse.status).toBe(200);
    expect(readResponse.body.data.map((table: { name: string }) => table.name)).toContain('orders');
    expect(readResponse.body.data.map((table: { name: string }) => table.name)).toContain('order_names');

    const source = app.dataSourceManager.dataSources.get(sourceKey) as PostgresDataSource;
    const loadResponse = await app
      .agent()
      .resource('dataSources')
      .loadTables({
        values: { dataSourceKey: sourceKey, tables: ['orders', 'order_names', 'composite_records'] },
      });
    expect(loadResponse.status).toBe(200);
    expect(source.collectionManager.hasCollection('orders')).toBe(true);
    expect(source.collectionManager.getCollection('order_names')?.options.view).toBe(true);
    expect(source.collectionManager.getCollection('order_names')?.filterTargetKey).toBe('id');
    expect(source.collectionManager.hasCollection('composite_records')).toBe(true);

    const collections = app.agent().resource('dataSources.collections', sourceKey);
    const createResponse = await collections.create({
      values: {
        name: 'managed_items',
        title: 'Managed items',
        fields: [{ name: 'name', type: 'string', interface: 'input', allowNull: false }],
      },
    });
    expect(createResponse.status, createResponse.text).toBe(200);
    const currentSource = app.dataSourceManager.dataSources.get(sourceKey) as PostgresDataSource;
    expect(
      currentSource.collectionManager.hasCollection('managed_items'),
      JSON.stringify({
        status: createResponse.status,
        response: createResponse.text,
        collections: currentSource.collectionManager.getCollections().map((collection) => collection.name),
      }),
    ).toBe(true);
    expect(await dataSource.collectionManager.discoverTables()).toContain('managed_items');
    const fields = app.agent().resource('dataSourcesCollections.fields', `${sourceKey}.managed_items`);
    const createFieldResponse = await fields.create({
      values: { name: 'note', type: 'string', interface: 'input' },
    });
    expect(createFieldResponse.status, createFieldResponse.text).toBe(200);
    const updateFieldResponse = await fields.update({ filterByTk: 'note', values: { unique: true } });
    expect(updateFieldResponse.status, updateFieldResponse.text).toBe(200);
    await expect(
      setupClient.query(
        `INSERT INTO "${testSchema}".managed_items (name, note) VALUES ('one', 'same'), ('two', 'same')`,
      ),
    ).rejects.toThrow();

    const deleteFieldResponse = await fields.destroy({ filterByTk: 'note' });
    expect(deleteFieldResponse.status, deleteFieldResponse.text).toBe(200);
    const remainingFields = await dataSource.collectionManager.discoverColumns('managed_items');
    expect(remainingFields.map((field) => field.column_name)).not.toContain('note');

    const zhI18n = await app.localeManager.getI18nInstance('zh-CN');
    zhI18n.addResourceBundle('zh-CN', NAMESPACE, { 'This collection is read-only': '此数据表为只读' }, true, true);
    const readOnlyFieldResponse = await app
      .agent()
      .resource('dataSourcesCollections.fields', `${sourceKey}.order_names`)
      .create({ locale: 'zh-CN', values: { name: 'extra', type: 'string', interface: 'input' } });
    expect(readOnlyFieldResponse.status).toBe(403);
    expect(readOnlyFieldResponse.text).toContain('此数据表为只读');
    expect(
      await app.db.getRepository('dataSourcesFields').findOne({
        filter: { name: 'extra', collectionName: 'order_names', dataSourceKey: sourceKey },
      }),
    ).toBeNull();
    const deniedPhysicalColumn = await setupClient.query(
      `SELECT column_name FROM information_schema.columns
       WHERE table_schema = $1 AND table_name = 'order_names' AND column_name = 'extra'`,
      [testSchema],
    );
    expect(deniedPhysicalColumn.rows).toHaveLength(0);

    const compositeFields = app.agent().resource('dataSourcesCollections.fields', `${sourceKey}.composite_records`);
    const applyFieldResponse = await compositeFields.apply({
      values: {
        name: 'sequence_number',
        type: 'integer',
        interface: 'integer',
        autoIncrement: true,
        allowNull: false,
      },
    });
    expect(applyFieldResponse.status, applyFieldResponse.text).toBe(200);
    const generatedRows = await setupClient.query<{ sequence_number: number }>(
      `INSERT INTO "${testSchema}".composite_records (tenant_id, record_id, value)
       VALUES (1, 1, 'identity field') RETURNING sequence_number`,
    );
    expect(generatedRows.rows[0].sequence_number).toBeGreaterThan(0);

    const rejectedIdentityUpdate = await compositeFields.update({
      filterByTk: 'sequence_number',
      values: { autoIncrement: false },
    });
    expect(rejectedIdentityUpdate.status).toBeGreaterThanOrEqual(400);
    const identityColumn = await setupClient.query<{ is_identity: string }>(
      `SELECT is_identity FROM information_schema.columns
       WHERE table_schema = $1 AND table_name = 'composite_records' AND column_name = 'sequence_number'`,
      [testSchema],
    );
    expect(identityColumn.rows[0].is_identity).toBe('YES');
    const savedIdentityField = await app.db.getRepository('dataSourcesFields').findOne({
      filter: { name: 'sequence_number', collectionName: 'composite_records', dataSourceKey: sourceKey },
    });
    expect(savedIdentityField?.get('autoIncrement')).toBe(true);

    const metadataRepo = app.db.getRepository('dataSourcesCollections');
    const collectionMetadata = await metadataRepo.findOne({
      filter: { name: 'orders', dataSourceKey: sourceKey },
    });
    if (!collectionMetadata) {
      await metadataRepo.create({ values: { name: 'orders', dataSourceKey: sourceKey } });
    }
    const rejectedDelete = await collections.destroy({ filterByTk: 'orders' });
    expect(rejectedDelete.status).toBe(500);
    expect(await metadataRepo.findOne({ filter: { name: 'orders', dataSourceKey: sourceKey } })).toBeTruthy();

    const deleteCollectionResponse = await collections.destroy({ filterByTk: 'managed_items', cascade: false });
    expect(deleteCollectionResponse.status).toBe(200);
    const remainingTables = await dataSource.collectionManager.discoverTables();
    expect(remainingTables).toContain('orders');
    expect(remainingTables).not.toContain('managed_items');
  });

  it('runs filtered and paginated SQL collections in read-only transactions', async () => {
    const collections = app.agent().resource('dataSources.collections', sourceKey);
    const createResponse = await collections.create({
      values: {
        name: 'paged_order_query',
        template: 'sql',
        sql: `
          SELECT id, name FROM orders
          UNION ALL SELECT 100, 'Page A'
          UNION ALL SELECT 101, 'Page B'
          UNION ALL SELECT 102, 'Page C'
        `,
        autoGenId: false,
        createdAt: false,
        updatedAt: false,
        createdBy: false,
        updatedBy: false,
        fields: [
          { name: 'id', type: 'integer', interface: 'integer' },
          { name: 'name', type: 'string', interface: 'input' },
        ],
      },
    });
    expect(createResponse.status, createResponse.text).toBe(200);

    const source = app.dataSourceManager.get(sourceKey) as PostgresDataSource;
    const collection = source.collectionManager.getCollection('paged_order_query');
    expect(collection?.constructor.name).toBe('PostgresSQLCollection');
    const rows = await collection.repository.find({
      filter: { id: { $gte: 100 } },
      sort: ['id'],
      limit: 1,
      offset: 1,
    });
    expect(rows.map((row) => row.get('id'))).toEqual([101]);
    const [pageRows, count] = await collection.repository.findAndCount({
      filter: { id: { $gte: 100 } },
      sort: ['id'],
      limit: 1,
      offset: 1,
    });
    expect(pageRows.map((row) => row.get('id'))).toEqual([101]);
    expect(count).toBe(3);

    const rejectedWrite = await app
      .agent()
      .post('/api/paged_order_query:create')
      .set('x-data-source', sourceKey)
      .send({ id: 200, name: 'Forbidden write' });
    expect(rejectedWrite.status).toBeGreaterThanOrEqual(400);
    expect(await collection.repository.find({ filter: { id: 200 } })).toHaveLength(0);
  });

  it('registers tree collections and preserves root and child reachability under filters', async () => {
    const collections = app.agent().resource('dataSources.collections', sourceKey);
    const createResponse = await collections.create({
      values: {
        name: 'category_tree',
        template: 'tree',
        tree: 'parentId',
        autoGenId: true,
        createdAt: false,
        updatedAt: false,
        createdBy: false,
        updatedBy: false,
        fields: [
          {
            name: 'id',
            type: 'integer',
            interface: 'id',
            primaryKey: true,
            autoIncrement: true,
            allowNull: false,
          },
          { name: 'name', type: 'string', interface: 'input', allowNull: false },
          { name: 'parentId', type: 'integer', interface: 'integer' },
          {
            name: 'parent',
            type: 'belongsTo',
            interface: 'm2o',
            target: 'category_tree',
            foreignKey: 'parentId',
            targetKey: 'id',
            treeParent: true,
          },
          {
            name: 'children',
            type: 'hasMany',
            interface: 'o2m',
            target: 'category_tree',
            foreignKey: 'parentId',
            sourceKey: 'id',
            treeChildren: true,
          },
        ],
      },
    });
    expect(createResponse.status, createResponse.text).toBe(200);

    const source = app.dataSourceManager.get(sourceKey) as PostgresDataSource;
    const collection = source.collectionManager.getCollection('category_tree');
    expect(collection?.constructor.name).toBe('PostgresTreeCollection');
    expect(collection?.options.postgresTree).toBe('parentId');
    expect(collection?.options.tree).toBeUndefined();
    expect(await dataSource.collectionManager.discoverTables()).toContain('category_tree');

    const repository = collection.repository;
    await source.collectionManager.db.sequelize.transaction(async (transaction) => {
      const root = await repository.create({ values: { name: 'Root' }, transaction });
      await repository.create({ values: { name: 'Child', parentId: root.get('id') }, transaction });
    });

    const tree = await repository.find({ tree: true });
    const root = tree.find((node) => node.get('name') === 'Root');
    expect(root?.get('children').map((node) => node.get('name'))).toEqual(['Child']);
    const filtered = await repository.find({ tree: true, filter: { name: 'Child' } });
    expect(filtered.map((node) => node.get('name'))).toEqual(['Child']);

    const child = await repository.findOne({ filter: { name: 'Child' } });
    await expect(
      source.collectionManager.db.sequelize.transaction((transaction) =>
        repository.update({ filterByTk: root?.get('id'), values: { parentId: child?.get('id') }, transaction }),
      ),
    ).rejects.toThrow('Cycle detected in tree collection');
    const unchangedTree = await repository.find({ tree: true });
    const unchangedRoot = unchangedTree.find((node) => node.get('name') === 'Root');
    expect(unchangedRoot?.get('children').map((node) => node.get('name'))).toEqual(['Child']);
  });

  it('restores saved collection and field metadata when auto discovery is disabled', async () => {
    const selected = new PostgresDataSource({
      ...testOptions,
      name: 'postgres-local-data-test',
      addAllCollections: false,
      autoDiscover: false,
    });
    try {
      await selected.load({
        localData: {
          orders: {
            name: 'orders',
            tableName: 'orders',
            title: 'Saved order title',
            fields: [{ name: 'name', type: 'string', interface: 'input', title: 'Saved field title' }],
          },
        },
      });

      const collections = selected.collectionManager.getCollections();
      expect(collections.map((collection) => collection.name)).toEqual(['orders']);
      expect(collections[0].options.title).toBe('Saved order title');
      expect(collections[0].getField('name')?.options.title).toBe('Saved field title');
    } finally {
      await selected.close();
    }
  });

  it('uses the PostgreSQL repository for CRUD on an introspected collection', async () => {
    const collection = dataSource.collectionManager.getCollection('orders');
    if (!collection) throw new Error('Expected the discovered orders collection');

    const repository = collection.repository;
    const created = await repository.create({ values: { name: 'Added order', external_code: 'new-code' } });
    const id = created.get('id');

    expect((await repository.find({ filter: { id } })).map((record) => record.get('name'))).toEqual(['Added order']);

    await repository.update({ filterByTk: id, values: { name: 'Updated order' } });
    expect((await repository.findOne({ filterByTk: id })).get('name')).toBe('Updated order');

    await repository.destroy({ filterByTk: id });
    expect(await repository.findOne({ filterByTk: id })).toBeNull();
  });

  it('preserves composite primary keys discovered from PostgreSQL', async () => {
    const collection = dataSource.collectionManager.getCollection('composite_records');
    const primaryKeyFields = collection
      ?.getFields()
      .filter((field) => field.options.primaryKey)
      .map((field) => field.name);

    expect(primaryKeyFields).toEqual(['tenant_id', 'record_id']);
  });

  it('prefers a UUID primary key over a separate identity column and preserves a saved target key', async () => {
    const inferred = dataSource.collectionManager.getCollection('uuid_identity_records');
    expect(inferred?.options.filterTargetKey).toBe('id');

    const selected = new PostgresDataSource({
      ...testOptions,
      name: 'postgres-saved-filter-target-test',
      addAllCollections: false,
      autoDiscover: false,
    });
    try {
      await selected.load({
        localData: {
          uuid_identity_records: {
            name: 'uuid_identity_records',
            tableName: 'uuid_identity_records',
            filterTargetKey: 'external_key',
          },
        },
      });
      expect(selected.collectionManager.getCollection('uuid_identity_records')?.options.filterTargetKey).toBe(
        'external_key',
      );
    } finally {
      await selected.close();
    }
  });

  it('adds, changes and removes physical fields, including unique indexes', async () => {
    const manager = dataSource.collectionManager;
    await manager.addField('orders', { name: 'nickname', type: 'string' });
    await manager.addField('orders', { name: 'unique_code', type: 'string' });
    await manager.updateField('orders', 'unique_code', { unique: true });

    const duplicateInsert = setupClient.query(
      `INSERT INTO "${testSchema}".orders (name, unique_code) VALUES ('First', 'duplicate')`,
    );
    await duplicateInsert;

    await expect(
      setupClient.query(`INSERT INTO "${testSchema}".orders (name, unique_code) VALUES ('Second', 'duplicate')`),
    ).rejects.toThrow();

    await manager.updateField('orders', 'unique_code', { unique: false });
    await setupClient.query(`INSERT INTO "${testSchema}".orders (name, unique_code) VALUES ('Second', 'duplicate')`);
    await manager.removeField('orders', 'nickname');

    const columns = await manager.discoverColumns('orders');
    expect(columns.map((column) => column.column_name)).not.toContain('nickname');
    expect(columns.map((column) => column.column_name)).toContain('unique_code');
  });

  it('refuses to drop a table with dependent objects unless cascade was selected', async () => {
    await expect(dataSource.collectionManager.dropTable('orders', false)).rejects.toThrow();

    const rows = await setupClient.query<{ table_name: string }>(
      `SELECT table_name FROM information_schema.tables WHERE table_schema = $1 AND table_name IN ('orders', 'order_names') ORDER BY table_name`,
      [testSchema],
    );
    expect(rows.rows.map((row) => row.table_name)).toEqual(['order_names', 'orders']);
  });
});

describe('PostgreSQL connection configuration', () => {
  it('verifies SSL certificates and applies a configured CA', async () => {
    const dataSource = new PostgresDataSource({
      host: '127.0.0.1',
      port: 5432,
      database: 'unused',
      username: 'unused',
      ssl: true,
      sslCa: 'test CA',
    });
    try {
      expect(dataSource.collectionManager.db.options.dialectOptions.ssl).toEqual({
        rejectUnauthorized: true,
        ca: 'test CA',
      });
      expect(dataSource.collectionManager.db.options.dialectOptions.connectionTimeoutMillis).toBeGreaterThan(0);
    } finally {
      await dataSource.close();
    }
  });
});
