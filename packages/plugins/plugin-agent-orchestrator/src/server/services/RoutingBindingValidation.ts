import type { Context } from '@nocobase/actions';
import { read } from '../utils/record-utils';

const routingFields = ['routingEnabled', 'routingRole', 'routingPrompt', 'llmService', 'model'] as const;
const identityFields = ['leaderUsername', 'subAgentUsername', 'enabled', 'harnessTag'] as const;
const bindingFields = [...identityFields, ...routingFields] as const;

type RoutingBinding = Partial<Record<(typeof bindingFields)[number], unknown>>;

export class RoutingCycleError extends Error {
  readonly status = 400;
  readonly statusCode = 400;
  readonly expose = true;

  constructor() {
    super('This binding would create a delegation cycle.');
  }
}

function nonBlank(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

function scalarBindingId(value: unknown) {
  return (
    (typeof value === 'string' && Boolean(value.trim())) ||
    (typeof value === 'number' && Number.isSafeInteger(value) && value > 0)
  );
}

/** Validate an opted-in binding after partial update values are merged with the stored record. */
export function routingBindingError(binding: RoutingBinding): string | null {
  if (binding.routingEnabled !== true) return null;
  if (!nonBlank(binding.leaderUsername) || !nonBlank(binding.subAgentUsername)) {
    return 'Routing requires a parent and a target employee.';
  }
  if (binding.leaderUsername.trim() === binding.subAgentUsername.trim()) {
    return 'An employee cannot delegate to itself.';
  }
  if (binding.routingRole !== 'specialist' && binding.routingRole !== 'worker') {
    return 'Choose a routing role for the target employee.';
  }
  if (
    (binding.llmService != null && typeof binding.llmService !== 'string') ||
    (binding.model != null && typeof binding.model !== 'string') ||
    Boolean(nonBlank(binding.llmService)) !== Boolean(nonBlank(binding.model))
  ) {
    return 'Select both an LLM service and a model, or leave both empty.';
  }
  if (
    binding.routingPrompt != null &&
    (typeof binding.routingPrompt !== 'string' || binding.routingPrompt.length > 4000)
  ) {
    return 'The routing description must be 4000 characters or fewer.';
  }
  return null;
}

/** Check the enabled routing graph without trusting labels or names generated by a model. */
export function routingWouldCycle(binding: RoutingBinding, rows: unknown[], excludeId?: unknown): boolean {
  if (binding.routingEnabled !== true || binding.enabled === false) return false;
  if (!nonBlank(binding.leaderUsername) || !nonBlank(binding.subAgentUsername)) return false;
  const parent = binding.leaderUsername.trim();
  const queue = [binding.subAgentUsername.trim()];
  const visited = new Set<string>();
  const edges = rows
    .filter((row) => excludeId == null || String(read(row, 'id')) !== String(excludeId))
    .filter((row) => read(row, 'enabled') !== false && read(row, 'routingEnabled') === true)
    .map((row) => ({ parent: read(row, 'leaderUsername'), target: read(row, 'subAgentUsername') }))
    .filter((edge): edge is { parent: string; target: string } => nonBlank(edge.parent) && nonBlank(edge.target));
  while (queue.length) {
    const current = queue.shift();
    if (!current) continue;
    if (current === parent) return true;
    if (visited.has(current)) continue;
    visited.add(current);
    for (const edge of edges) {
      if (edge.parent.trim() === current) queue.push(edge.target.trim());
    }
  }
  return false;
}

/** Run after ACL so this validation cannot replace collection or association authorization. */
async function validateRoutingBinding(ctx: Context, next: () => Promise<unknown>) {
  const { resourceName, actionName, params } = ctx.action || {};
  if (resourceName !== 'orchestratorConfig' || !['create', 'update'].includes(actionName)) return next();
  const values = params?.values;
  if (!values || typeof values !== 'object') return next();
  if (Array.isArray(values)) {
    if (
      values.some(
        (item) =>
          item && typeof item === 'object' && [...routingFields, ...identityFields].some((field) => field in item),
      )
    ) {
      return ctx.throw(400, ctx.t('Update routing settings for one binding at a time.'));
    }
    return next();
  }
  const patch = values as RoutingBinding;
  if ('routingEnabled' in patch && typeof patch.routingEnabled !== 'boolean') {
    return ctx.throw(400, ctx.t('Routing enabled must be a boolean.'));
  }
  let current: unknown;
  if (actionName === 'update') {
    const key = params.filterByTk;
    if (!scalarBindingId(key)) {
      if (routingFields.some((field) => field in patch)) {
        return ctx.throw(400, ctx.t('Update routing settings for one binding at a time.'));
      }
      if (identityFields.some((field) => field in patch)) {
        if (key != null && (!Array.isArray(key) || !key.length || !key.every(scalarBindingId))) {
          return ctx.throw(400, ctx.t('Update routing settings for one binding at a time.'));
        }
        const filter = params.filter && typeof params.filter === 'object' ? params.filter : {};
        const targets = Array.isArray(key) ? { id: key } : {};
        const affected = await ctx.db.getRepository('orchestratorConfig').findOne({
          filter: { $and: [filter, targets, { routingEnabled: true }] },
        });
        if (affected) return ctx.throw(400, ctx.t('Update routing settings for one binding at a time.'));
      }
      return next();
    }
    current = await ctx.db.getRepository('orchestratorConfig').findOne({ filterByTk: key });
    if (!current) return next();
  }
  const merged: RoutingBinding = {};
  for (const field of bindingFields) {
    merged[field] = field in patch ? patch[field] : read(current, field);
  }
  const error = routingBindingError(merged);
  if (error) return ctx.throw(400, ctx.t(error));
  if (merged.routingEnabled === true && merged.enabled !== false) {
    const rows = await ctx.db.getRepository('orchestratorConfig').find({
      filter: { routingEnabled: true, enabled: true },
    });
    if (routingWouldCycle(merged, rows, actionName === 'update' ? params.filterByTk : undefined)) {
      return ctx.throw(400, ctx.t('This binding would create a delegation cycle.'));
    }
  }
  return next();
}

export async function validateRoutingBindingAction(ctx: Context, next: () => Promise<unknown>) {
  try {
    return await validateRoutingBinding(ctx, next);
  } catch (error) {
    if (error instanceof RoutingCycleError) return ctx.throw(400, ctx.t(error.message));
    throw error;
  }
}
